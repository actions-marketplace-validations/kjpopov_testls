/// All known primes.
#[must_use]
pub fn known_dh_primes() -> &'static [KnownPrime] {
    KNOWN_PRIMES
}

/// The published prime equal to `prime` (big-endian, leading zeros
/// allowed), if any.
#[must_use]
pub fn known_dh_prime(prime: &[u8]) -> Option<&'static KnownPrime> {
    let start = prime.iter().position(|&b| b != 0)?;
    let digits = &prime[start..];
    KNOWN_PRIMES.iter().find(|k| hex_equals(k.hex, digits))
}

/// Whether upper-case `hex` encodes exactly `bytes`.
fn hex_equals(hex: &str, bytes: &[u8]) -> bool {
    const DIGITS: &[u8; 16] = b"0123456789ABCDEF";
    hex.len() == bytes.len() * 2
        && hex.as_bytes().chunks(2).zip(bytes).all(|(pair, &b)| {
            pair[0] == DIGITS[usize::from(b >> 4)] && pair[1] == DIGITS[usize::from(b & 0x0f)]
        })
}

#[cfg(test)]
mod tests {
    //! Unit tests for the Diffie-Hellman prime table.
    use super::*;

    /// Decode upper-case hex for the tests.
    fn decode(hex: &str) -> Vec<u8> {
        (0..hex.len())
            .step_by(2)
            .map(|i| u8::from_str_radix(&hex[i..i + 2], 16).unwrap())
            .collect()
    }

    /// Entries are in order, sized as named, odd, upper-case hex without
    /// leading zeros, and only the RFC 7919 groups are flagged `ffdhe`.
    #[test]
    fn table_is_well_formed() {
        let sizes: Vec<(&str, usize)> = known_dh_primes()
            .iter()
            .map(|k| (k.name, k.hex.len() * 4))
            .collect();
        assert_eq!(
            sizes,
            [
                ("Oakley group 1", 768),
                ("Oakley group 2", 1024),
                ("MODP group 5", 1536),
                ("MODP group 14", 2048),
                ("MODP group 15", 3072),
                ("MODP group 16", 4096),
                ("MODP group 17", 6144),
                ("MODP group 18", 8192),
                ("RFC 5114 1024-bit group", 1024),
                ("RFC 5114 2048-bit group (224-bit subgroup)", 2048),
                ("RFC 5114 2048-bit group (256-bit subgroup)", 2048),
                ("ffdhe2048", 2048),
                ("ffdhe3072", 3072),
                ("ffdhe4096", 4096),
                ("ffdhe6144", 6144),
                ("ffdhe8192", 8192),
            ]
        );
        for k in known_dh_primes() {
            assert!(
                k.hex
                    .bytes()
                    .all(|c| c.is_ascii_digit() || (b'A'..=b'F').contains(&c)),
                "{}",
                k.name
            );
            assert!(!k.hex.starts_with('0'), "{}", k.name);
            // Every safe prime used for DH is odd.
            assert!(decode(k.hex).last().unwrap() & 1 == 1, "{}", k.name);
            assert_eq!(k.ffdhe, k.source.starts_with("RFC 7919"), "{}", k.name);
        }
    }

    /// Lookup matches exact and zero-padded primes and rejects altered,
    /// truncated, empty and all-zero input.
    #[test]
    fn lookup() {
        let modp14 = decode(known_dh_primes()[3].hex);
        assert_eq!(known_dh_prime(&modp14).unwrap().name, "MODP group 14");
        let mut padded = vec![0, 0];
        padded.extend_from_slice(&modp14);
        assert_eq!(known_dh_prime(&padded).unwrap().name, "MODP group 14");
        let mut other = modp14.clone();
        *other.last_mut().unwrap() ^= 2;
        assert!(known_dh_prime(&other).is_none());
        assert!(known_dh_prime(&modp14[1..]).is_none());
        assert!(known_dh_prime(&[]).is_none());
        assert!(known_dh_prime(&[0, 0]).is_none());
        let ffdhe = decode(known_dh_primes()[11].hex);
        assert!(known_dh_prime(&ffdhe).unwrap().ffdhe);
    }
}
