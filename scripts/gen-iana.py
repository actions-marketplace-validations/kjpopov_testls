#!/usr/bin/env python3
"""Generate crates/testls-data/src/generated.rs from the IANA CSV snapshots.

Usage: python3 scripts/gen-iana.py

The CSV files in crates/testls-data/iana/ are verbatim downloads from
https://www.iana.org/assignments/tls-parameters/. Refresh them with
scripts/fetch-iana.sh, then re-run this script and commit both.
"""

import csv
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
IANA = ROOT / "crates" / "testls-data" / "iana"
OUT = ROOT / "crates" / "testls-data" / "src" / "generated.rs"

RECOMMENDED = {"Y": "Yes", "N": "No", "D": "Discouraged", "": "No"}


def rows(name):
    with open(IANA / name, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            yield {k: " ".join(v.split()) for k, v in row.items()}


def skip(desc):
    return desc in ("Unassigned", "Reserved") or desc.startswith("Reserved ")


def cipher_suites():
    out = []
    for row in rows("tls-parameters-4.csv"):
        m = re.fullmatch(r"0x([0-9A-F]{2}),0x([0-9A-F]{2})", row["Value"])
        if not m or skip(row["Description"]):
            continue
        out.append(
            (
                int(m.group(1), 16) << 8 | int(m.group(2), 16),
                row["Description"],
                RECOMMENDED[row["Recommended"]],
            )
        )
    return out


def groups():
    out = []
    for row in rows("tls-parameters-8.csv"):
        if not row["Value"].isdigit() or skip(row["Description"]):
            continue
        out.append((int(row["Value"]), row["Description"], RECOMMENDED[row["Recommended"]]))
    return out


def signature_schemes():
    out = []
    for row in rows("tls-signaturescheme.csv"):
        if not re.fullmatch(r"0x[0-9A-Fa-f]{4}", row["Value"]) or skip(row["Description"]):
            continue
        out.append((int(row["Value"], 16), row["Description"], RECOMMENDED[row["Recommended"]]))
    return out


def emit(f, const, ty, entries):
    f.write(f"pub(crate) const {const}: &[{ty}] = &[\n")
    for value, name, rec in entries:
        f.write(
            f"    {ty} {{ id: 0x{value:04x}, name: {name!r}, recommended: Recommended::{rec} }},\n".replace(
                "'", '"'
            )
        )
    f.write("];\n\n")


def main():
    suites = cipher_suites()
    for table in (suites, groups(), signature_schemes()):
        ids = [v for v, _, _ in table]
        assert ids == sorted(ids) and len(ids) == len(set(ids)), "table must be sorted and unique"
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// @generated by scripts/gen-iana.py from crates/testls-data/iana/*.csv. Do not edit.\n\n")
        f.write("use crate::{CipherSuiteInfo, GroupInfo, Recommended, SignatureSchemeInfo};\n\n")
        emit(f, "CIPHER_SUITES", "CipherSuiteInfo", suites)
        emit(f, "GROUPS", "GroupInfo", groups())
        emit(f, "SIGNATURE_SCHEMES", "SignatureSchemeInfo", signature_schemes())
    subprocess.run(["rustfmt", "--edition", "2024", str(OUT)], check=True)


if __name__ == "__main__":
    main()
