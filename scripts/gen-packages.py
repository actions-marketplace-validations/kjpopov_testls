#!/usr/bin/env python3
"""Generate the Homebrew, Scoop and winget manifests for a release.

Usage: python3 scripts/gen-packages.py SHA256SUMS

SHA256SUMS is the checksum file of a published GitHub release
(`gh release download vX.Y.Z -p SHA256SUMS`). The version and the archive
hashes are read from it, and the script rewrites:

- Formula/testls.rb (Homebrew tap: this repository)
- bucket/testls.json (Scoop bucket: this repository)
- packaging/winget/X.Y.Z/*.yaml (to submit to microsoft/winget-pkgs)
"""

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
REPO = "https://github.com/kjpopov/testls"
DESCRIPTION = "TLS/SSL scanner for the web era, inspired by testssl.sh."
TARGETS = [
    "aarch64-apple-darwin",
    "x86_64-apple-darwin",
    "aarch64-unknown-linux-musl",
    "x86_64-unknown-linux-musl",
    "x86_64-pc-windows-msvc",
]
ARCHIVE = re.compile(
    r"^testls-v(\d+\.\d+\.\d+(?:-[0-9A-Za-z.]+)?)-(" + "|".join(map(re.escape, TARGETS)) + r")\.(?:tar\.gz|zip)$"
)
WINGET_ID = "Kjpopov.Testls"
WINGET_SCHEMA = "1.10.0"


def read_sums(path):
    """Returns (version, {target: (file name, sha256)}) from SHA256SUMS."""
    version = None
    archives = {}
    for line in pathlib.Path(path).read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        digest, name = line.split(maxsplit=1)
        name = name.lstrip("*")
        match = ARCHIVE.match(name)
        if not match or not re.fullmatch(r"[0-9a-f]{64}", digest):
            sys.exit(f"unexpected SHA256SUMS line: {line}")
        if version not in (None, match[1]):
            sys.exit(f"SHA256SUMS mixes versions {version} and {match[1]}")
        version = match[1]
        archives[match[2]] = (name, digest)
    missing = [t for t in TARGETS if t not in archives]
    if missing:
        sys.exit(f"SHA256SUMS lacks archives for {', '.join(missing)}")
    return version, archives


def url(version, name):
    """Returns the download URL of release asset `name`."""
    return f"{REPO}/releases/download/v{version}/{name}"


def has_generated_docs(version):
    """Tells whether the binary has the completions and man subcommands (after 0.3.0)."""
    core = tuple(int(part) for part in version.split("-")[0].split("."))
    return core > (0, 3, 0)


def formula(version, archives):
    """Renders the Homebrew formula."""

    def block(target):
        name, digest = archives[target]
        return f'      url "{url(version, name)}"\n      sha256 "{digest}"\n'

    install = '    bin.install "testls"\n'
    if has_generated_docs(version):
        install += (
            '    generate_completions_from_executable(bin/"testls", "completions", shells: [:bash, :zsh, :fish])\n'
            "    man1.mkpath\n"
            '    system bin/"testls", "man", "--dir", man1\n'
        )
    return (
        "# Generated by scripts/gen-packages.py; do not edit by hand.\n"
        "class Testls < Formula\n"
        f'  desc "{DESCRIPTION.removesuffix(".")}"\n'
        f'  homepage "{REPO}"\n'
        f'  version "{version}"\n'
        '  license any_of: ["MIT", "Apache-2.0"]\n'
        "\n"
        "  on_macos do\n"
        "    on_arm do\n"
        f"{block('aarch64-apple-darwin')}"
        "    end\n"
        "    on_intel do\n"
        f"{block('x86_64-apple-darwin')}"
        "    end\n"
        "  end\n"
        "\n"
        "  on_linux do\n"
        "    on_arm do\n"
        f"{block('aarch64-unknown-linux-musl')}"
        "    end\n"
        "    on_intel do\n"
        f"{block('x86_64-unknown-linux-musl')}"
        "    end\n"
        "  end\n"
        "\n"
        "  def install\n"
        f"{install}"
        "  end\n"
        "\n"
        "  test do\n"
        '    assert_match version.to_s, shell_output("#{bin}/testls --version")\n'
        "  end\n"
        "end\n"
    )


def scoop(version, archives):
    """Renders the Scoop manifest."""
    name, digest = archives["x86_64-pc-windows-msvc"]
    folder = name.removesuffix(".zip")
    manifest = {
        "version": version,
        "description": DESCRIPTION,
        "homepage": REPO,
        "license": "MIT|Apache-2.0",
        "architecture": {
            "64bit": {"url": url(version, name), "hash": digest, "extract_dir": folder}
        },
        "bin": "testls.exe",
        "checkver": {"github": REPO},
        "autoupdate": {
            "architecture": {
                "64bit": {
                    "url": url("$version", "testls-v$version-x86_64-pc-windows-msvc.zip"),
                    "extract_dir": "testls-v$version-x86_64-pc-windows-msvc",
                }
            },
            "hash": {"url": "$baseurl/SHA256SUMS"},
        },
    }
    return json.dumps(manifest, indent=4) + "\n"


def winget(version, archives):
    """Renders the winget manifests as {file name: text}."""
    name, digest = archives["x86_64-pc-windows-msvc"]
    folder = name.removesuffix(".zip")
    header = (
        "# Generated by scripts/gen-packages.py; do not edit by hand.\n"
        "# yaml-language-server: $schema=https://aka.ms/winget-manifest.{kind}."
        f"{WINGET_SCHEMA}.schema.json\n"
        f"PackageIdentifier: {WINGET_ID}\n"
        f"PackageVersion: {version}\n"
    )
    footer = "ManifestType: {kind}\n" f"ManifestVersion: {WINGET_SCHEMA}\n"

    def manifest(kind, body):
        return header.format(kind=kind) + body + footer.format(kind=kind)

    return {
        f"{WINGET_ID}.yaml": manifest("version", "DefaultLocale: en-US\n"),
        f"{WINGET_ID}.locale.en-US.yaml": manifest(
            "defaultLocale",
            "PackageLocale: en-US\n"
            "Publisher: Krasimir Popov\n"
            f"PublisherUrl: {REPO}\n"
            "PackageName: testls\n"
            f"PackageUrl: {REPO}\n"
            "License: MIT OR Apache-2.0\n"
            f"LicenseUrl: {REPO}#license\n"
            f"ShortDescription: {DESCRIPTION}\n"
            "Moniker: testls\n"
            "Tags:\n- tls\n- ssl\n- security\n- scanner\n"
            f"ReleaseNotesUrl: {REPO}/releases/tag/v{version}\n",
        ),
        f"{WINGET_ID}.installer.yaml": manifest(
            "installer",
            "InstallerType: zip\n"
            "NestedInstallerType: portable\n"
            "NestedInstallerFiles:\n"
            f"- RelativeFilePath: {folder}\\testls.exe\n"
            "  PortableCommandAlias: testls\n"
            "Installers:\n"
            "- Architecture: x64\n"
            f"  InstallerUrl: {url(version, name)}\n"
            f"  InstallerSha256: {digest.upper()}\n",
        ),
    }


def main():
    """Writes every manifest for the release described by argv[1]."""
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    version, archives = read_sums(sys.argv[1])
    outputs = {
        ROOT / "Formula" / "testls.rb": formula(version, archives),
        ROOT / "bucket" / "testls.json": scoop(version, archives),
    }
    winget_dir = ROOT / "packaging" / "winget"
    for old in winget_dir.glob("*/*.yaml"):
        old.unlink()
    for name, text in winget(version, archives).items():
        outputs[winget_dir / version / name] = text
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(path.relative_to(ROOT))
    for empty in winget_dir.iterdir():
        if empty.is_dir() and not any(empty.iterdir()):
            empty.rmdir()


if __name__ == "__main__":
    main()
